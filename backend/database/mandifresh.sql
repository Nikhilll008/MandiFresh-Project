SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------------
-- Table: crops
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS `crops`;
CREATE TABLE `crops` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(100) NOT NULL,
  `category` VARCHAR(50) DEFAULT NULL,
  `unit` VARCHAR(20) NOT NULL DEFAULT 'quintal',
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME DEFAULT NULL,
  `updated_at` DATETIME DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
-- Table: mandi_prices
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS `mandi_prices`;
CREATE TABLE `mandi_prices` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `crop_id` INT UNSIGNED NOT NULL,
  `mandi_name` VARCHAR(150) NOT NULL,
  `price_date` DATE NOT NULL,
  `current_price` DECIMAL(10,2) NOT NULL,
  `previous_price` DECIMAL(10,2) NOT NULL DEFAULT 0,
  `created_at` DATETIME DEFAULT NULL,
  `updated_at` DATETIME DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `crop_id` (`crop_id`),
  KEY `price_date` (`price_date`),
  KEY `mandi_name` (`mandi_name`),
  CONSTRAINT `fk_mandi_prices_crop` FOREIGN KEY (`crop_id`) REFERENCES `crops` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
-- Table: profit_calculations
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS `profit_calculations`;
CREATE TABLE `profit_calculations` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `crop_name` VARCHAR(100) NOT NULL,
  `quantity_kg` DECIMAL(12,2) NOT NULL,
  `production_cost_per_kg` DECIMAL(10,2) NOT NULL,
  `selling_price_per_kg` DECIMAL(10,2) NOT NULL,
  `revenue` DECIMAL(14,2) NOT NULL,
  `total_cost` DECIMAL(14,2) NOT NULL,
  `net_profit` DECIMAL(14,2) NOT NULL,
  `profit_margin` DECIMAL(6,2) NOT NULL,
  `break_even_price` DECIMAL(10,2) NOT NULL,
  `suggested_price` DECIMAL(10,2) NOT NULL,
  `ip_address` VARCHAR(45) DEFAULT NULL,
  `created_at` DATETIME DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

